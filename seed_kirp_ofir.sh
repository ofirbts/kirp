    -H "Content-Type: application/json" \
    -H "Authorization: Bearer $TOKEN" \
    -d "{
      \"tenant_id\": \"$TENANT\",
      \"space_id\": \"$SPACE\",
      \"user_id\": \"$USER\",
      \"content\": \"$content\"
    }" > /dev/null
}

